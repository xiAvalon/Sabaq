// Writes supabase/seed_questions.sql from the bundled question bank, so the server checks
// answers against exactly the questions the app shows. Run after editing questions:
//   npm run seed:questions
import { writeFileSync } from 'node:fs';
import { QUESTION_BANK } from '../src/data/questions/index.js';
import { getInputKind, getQuestionType } from '../src/engine/questionTypes.js';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;

const rows = QUESTION_BANK.map((q) => {
  const kind = getInputKind(q);
  const accept = kind === 'text' ? q.accept ?? [] : [];
  return `(${[lit(q.id), lit(q.category), q.difficulty, lit(q.type), lit(kind), json(q.answer), json(accept), q.tolerance ?? 0, getQuestionType(q.type).speedFriendly].join(', ')})`;
});

const sql = `-- Generated by scripts/build-question-seed.mjs from src/data/questions. Do not edit by hand.
-- ${QUESTION_BANK.length} questions.
begin;
delete from public.questions where id not in (${QUESTION_BANK.map((q) => lit(q.id)).join(', ')});
insert into public.questions (id, category, difficulty, type, kind, answer, accept, tolerance, speed) values
${rows.join(',\n')}
on conflict (id) do update set
  category = excluded.category, difficulty = excluded.difficulty, type = excluded.type, kind = excluded.kind,
  answer = excluded.answer, accept = excluded.accept, tolerance = excluded.tolerance, speed = excluded.speed;
commit;
`;
writeFileSync(new URL('../supabase/seed_questions.sql', import.meta.url), sql);
console.log(`Wrote ${QUESTION_BANK.length} questions to supabase/seed_questions.sql`);
